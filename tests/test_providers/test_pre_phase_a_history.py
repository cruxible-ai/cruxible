class _Bodies:
    def __init__(self, bodies: dict[str, str]) -> None:
        self._bodies = {digest: base64.b64decode(value) for digest, value in bodies.items()}

    def read(self, digest: str, *, access: object) -> bytes:
        return self._bodies[digest]


def _records(run: dict[str, Any]) -> tuple[StoredProcedureJournalRecordV1, ...]:
    return tuple(StoredProcedureJournalRecordV1.model_validate(item) for item in run["records"])


def _payloads(run: dict[str, Any]) -> list[tuple[str, Any]]:
    bodies = _Bodies(run["bodies"])
    return [
        (
            stored.record.event_kind,
            parse_journal_payload(bodies.read(stored.record.payload_digest, access=None)),
        )
        for stored in _records(run)
    ]


@pytest.mark.parametrize("name", sorted(HISTORY["registrations"]))
def test_pre_removal_registrations_parse_render_and_accept_byte_identically(name: str) -> None:
    held = HISTORY["registrations"][name]
    content = held["bytes"].encode("utf-8")
    registration = parse_provider_interface(
        content, path=provider_interface_path(json.loads(content)["interface_id"])
    )
    assert render_provider_interface(registration) == content
    assert provider_interface_digest(registration).tagged == held["artifact_digest"]
    law = evaluate_provider_interface_law(
        registration, path=provider_interface_path(registration.interface_id), predecessor=None
    )
    assert law.verdict == "accepted" and law.artifact_digest == held["artifact_digest"]


@pytest.mark.parametrize("run_name", ["call_run", "source_run"])
def test_pre_removal_run_records_parse_and_redigest_exactly(run_name: str) -> None:
    run = HISTORY[run_name]
    seen: set[str] = set()
    for kind, payload in _payloads(run):
        if kind == "admission_bound":
            bound = parse_admission_payload(payload)
            assert isinstance(bound, ProcedureAdmissionBoundPayloadV5)
            assert bound.admission.tag == "playbill-procedure-run-admission-v5"
            (binding,) = bound.admission.resolved_provider_bindings
            assert binding.tag == "playbill-procedure-provider-binding-v2"
            (occurrence,) = bound.acquisition_plan.external_occurrences
            assert occurrence.accepted_bucket_selectors and occurrence.classifier_digest
            model: Any = bound
        elif kind == "provider_invocation_started":
            model = ProviderInvocationStarted.model_validate(payload)
            assert model.input_bucket is not None
        elif kind == "provider_invocation_completed":
            model = ProviderInvocationCompleted.model_validate(payload)
            assert model.receipt.input_bucket is not None
        else:
            continue
        seen.add(kind)
        assert canonical_bytes(model.model_dump(mode="json")) == canonical_bytes(payload)
    assert seen == {
        "admission_bound",
        "provider_invocation_started",
        "provider_invocation_completed",
    }


@pytest.mark.parametrize("run_name", ["call_run", "source_run"])
def test_pre_removal_runs_reproduce_their_v6_receipt_and_digest(
    run_name: str, monkeypatch: pytest.MonkeyPatch
) -> None:
    run = HISTORY[run_name]
    records = _records(run)
    bodies = _Bodies(run["bodies"])

    class _Instance:
        def body_store(self) -> _Bodies:
            return bodies

    monkeypatch.setattr(service, "_records_for_run", lambda *_args: records)
    state = service._state_from_records(_Instance(), run_id=run["run_id"])  # type: ignore[arg-type]  # noqa: SLF001
    assert state.receipt is not None and state.receipt.tag == "playbill-procedure-run-receipt-v6"
    assert canonical_bytes(state.receipt.model_dump(mode="json")) == canonical_bytes(run["receipt"])
    assert state.receipt_digest == run["receipt_digest"]


def test_a_pre_removal_capture_keeps_its_measured_bucket_and_digest() -> None:
    run = HISTORY["source_run"]
    content = base64.b64decode(run["capture_envelope"])
    envelope = parse_capture_envelope(content)
    assert isinstance(envelope, CaptureEnvelope)
    assert render_capture_envelope(envelope) == content
    assert capture_digest(envelope).tagged == run["capture_digest"]
    evidence = envelope.production_evidence
    assert isinstance(evidence, ProviderInvocationCaptureEvidence)
    assert evidence.input_bucket is not None


def test_pinned_package_documents_survive_contract_only_registration() -> None:
    """Read the same pinned exports, now registering their contract alone.

    Historical registration bytes remain covered above; new registrations use
    contract-qualified identities and intentionally differ from the old lowering.
    """

    checkout = provider_checkout_path()
    if checkout is None:
        pytest.skip("set CRUXIBLE_PROVIDERS_CHECKOUT to compare against the pinned packages")
    from cruxible_core.providers.package_metadata import read_package_registration

    packages = {
        path.parent.parent.parent.name: path.parent
        for path in sorted(checkout.glob("packages/*/src/*/registration.json"))
    }
    assert set(packages) == set(LOWERING["packages"])
    for name, root in packages.items():
        expected = LOWERING["packages"][name]
        document = read_package_registration(root)
        assert (
            hashlib.sha256(canonical_bytes(document.model_dump(mode="json"))).hexdigest()
            == expected["document_sha256"]
        ), name
        registrations = document.interface_registrations()
        assert {item.interface_id for item in registrations} == set(expected["registrations"])
        exports = {item.interface_id: item for item in document.interfaces}
        for item in registrations:
            assert isinstance(item, ProviderInterfaceContract)
            exported = exports[item.interface_id]
            assert interface_definition_digest(item) == exported.interface_digest
            assert interface_definition_bytes(item) == canonical_bytes(exported.definition)
            assert item.identity.name.startswith(item.interface_id + "/")
            historical = expected["registrations"][item.interface_id]
            assert provider_interface_digest(item).tagged != historical["artifact_digest"]
            assert (
                hashlib.sha256(render_provider_interface(item)).hexdigest()
                != historical["bytes_sha256"]
            )
