#!/usr/bin/env python3
"""Render the bundled base kit from its authored sources (design note §7.4.2).

Sources live in ``scripts/base_kit/``: ``kit.json`` (kit id, version, owned
prefixes), and one file per Contract, capability and CaptureKind at the kit
artifact path it renders to (``contracts/<name>/v<N>.json``,
``capabilities/<name>/v<N>.json``, ``capture-contracts/<name>.json``). A source
names the Contracts it nests or pins as ``{name, version}`` (a capability's
``in``/``out`` as ``name@N``, a layout's record-set ``row`` as ``{name,
version}``), without digests: this script pins each one to the digest of the
Contract it renders, nested ones first. A CaptureKind source is the ordinary
CaptureKind authoring input (name, shape, grade, decoding, layout); this script
lowers it the way authoring does.

It writes the kit directory ``src/cruxible_core/kits/base/`` (``cruxible-kit.json``
and ``artifacts/``) and ``src/cruxible_core/kits/base_kit_pin.py``, the one
constant holding the bundled version and content digest that core checks the
directory against. ``--check`` renders in memory and exits 1 when anything on
disk differs; CI runs it.

Usage::

    python scripts/build_base_kit.py          # write the directory and the constant
    python scripts/build_base_kit.py --check  # fail when they differ from the sources
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Mapping
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
SOURCE = REPO_ROOT / "scripts" / "base_kit"
KIT_DIRECTORY = REPO_ROOT / "src" / "cruxible_core" / "kits" / "base"
PIN_MODULE = REPO_ROOT / "src" / "cruxible_core" / "kits" / "base_kit_pin.py"

PIN_TEMPLATE = '''"""The bundled base kit's version and content digest.

Generated by ``scripts/build_base_kit.py`` from ``scripts/base_kit/``; do not
edit. Core refuses to load a base kit directory that differs from it.
"""

from __future__ import annotations

from cruxible_core.kits import BundledKitPin

BASE_KIT_PIN = BundledKitPin(
    kit_id="{kit_id}",
    version="{version}",
    content_digest="{content_digest}",
)

__all__ = ["BASE_KIT_PIN"]
'''


def _sources(root: Path, family: str) -> dict[str, dict[str, Any]]:
    directory = root / family
    if not directory.is_dir():
        return {}
    return {
        path.relative_to(root).as_posix(): json.loads(path.read_bytes())
        for path in sorted(directory.rglob("*.json"))
    }


def _nested_contracts(value: Any) -> list[tuple[str, int]]:
    found: list[tuple[str, int]] = []
    if isinstance(value, Mapping):
        target = value.get("contract")
        if value.get("kind") == "contract" and isinstance(target, Mapping):
            found.append((str(target["name"]), int(target["version"])))
        for item in value.values():
            found.extend(_nested_contracts(item))
    elif isinstance(value, list):
        for item in value:
            found.extend(_nested_contracts(item))
    return found


def render(source: Path = SOURCE) -> tuple[dict[str, bytes], bytes, str]:
    """``(artifacts, manifest bytes, pin module text)`` the sources render to."""

    from cruxible_client.contracts.canonical import pretty_canonical_bytes
    from cruxible_client.contracts.capabilities import (
        capability_path,
        render_capability,
        validate_capability,
    )
    from cruxible_client.contracts.kits import KitArtifact, KitManifest
    from cruxible_client.contracts.shapes import (
        ContractRef,
        contract_digest,
        contract_path,
        pin_contract_refs,
        render_contract,
        validate_contract,
    )
    from cruxible_core.claims.closure import parse_dependency_artifact

    kit = json.loads((source / "kit.json").read_bytes())
    contract_sources = _sources(source, "contracts")
    by_ref = {
        (str(payload["name"]), int(payload["version"])): (path, payload)
        for path, payload in contract_sources.items()
    }
    artifacts: dict[str, bytes] = {}
    digests: dict[tuple[str, int], str] = {}
    visiting: set[tuple[str, int]] = set()

    def contract(ref: tuple[str, int]) -> str:
        if ref in digests:
            return digests[ref]
        if ref not in by_ref:
            raise SystemExit(f"base kit source names {ref[0]}@{ref[1]}, which has no source")
        if ref in visiting:
            raise SystemExit(f"base kit Contracts nest each other in a cycle through {ref}")
        visiting.add(ref)
        path, payload = by_ref[ref]
        for nested in _nested_contracts(payload.get("fields", {})):
            contract(nested)
        visiting.discard(ref)

        def pin(item: ContractRef) -> ContractRef:
            return item.model_copy(update={"digest": digests[(item.name, item.version)]})

        rendered = pin_contract_refs(validate_contract(payload), pin)
        expected = contract_path(rendered.name, rendered.version)
        if path != expected:
            raise SystemExit(f"base kit source {path} declares {expected}")
        artifacts[path] = render_contract(rendered)
        digests[ref] = contract_digest(rendered).tagged
        return digests[ref]

    for ref in sorted(by_ref):
        contract(ref)
    for path, payload in _sources(source, "capabilities").items():
        pinned = dict(payload)
        for role in ("in", "out"):
            name, _, version = str(payload[role]).rpartition("@")
            pinned[role] = {
                "name": name,
                "version": int(version),
                "digest": contract((name, int(version))),
            }
        capability = validate_capability(pinned)
        expected = capability_path(capability.name, capability.version)
        if path != expected:
            raise SystemExit(f"base kit source {path} declares {expected}")
        artifacts[path] = render_capability(capability)
    for path, payload in _sources(source, "capture-contracts").items():
        artifacts[path] = _capture_kind(path, payload, contract)
    manifest = KitManifest(
        kit_id=kit["kit_id"],
        version=kit["version"],
        owns=tuple(kit["owns"]),
        artifacts=tuple(
            KitArtifact(
                path=path,
                artifact_digest=_digest(parse_dependency_artifact(path, content), path),
            )
            for path, content in sorted(artifacts.items())
        ),
    )
    pin_text = PIN_TEMPLATE.format(
        kit_id=manifest.kit_id,
        version=manifest.version,
        content_digest=manifest.content_digest,
    )
    return artifacts, pretty_canonical_bytes(manifest.model_dump(mode="json")), pin_text


def _capture_kind(path: str, payload: dict[str, Any], contract: Any) -> bytes:
    """One CaptureKind, lowered from its authoring input with its layout rows pinned."""

    from cruxible_client.contracts.capture_contract_inputs import (
        CaptureContractInputRecord,
        lower_capture_contract_input,
    )
    from cruxible_client.contracts.captures import capture_contract_path, render_capture_contract

    pinned = json.loads(json.dumps(payload))
    for record_set in (pinned.get("layout") or {}).get("records", {}).values():
        row = record_set["row"]
        record_set["row"] = {**row, "digest": contract((str(row["name"]), int(row["version"])))}
    record = CaptureContractInputRecord.model_validate(pinned)
    expected = capture_contract_path(record.name)
    if path != expected:
        raise SystemExit(f"base kit source {path} declares {expected}")
    return render_capture_contract(lower_capture_contract_input(record, named=True))


def _digest(state: Any, path: str) -> str:
    if state is None:
        raise SystemExit(f"base kit artifact {path} is not a definition artifact")
    return str(state.artifact_digest)


def _on_disk(directory: Path) -> dict[str, bytes]:
    root = directory / "artifacts"
    if not root.is_dir():
        return {}
    return {
        path.relative_to(root).as_posix(): path.read_bytes()
        for path in sorted(root.rglob("*"))
        if path.is_file()
    }


def differences(
    source: Path = SOURCE, directory: Path = KIT_DIRECTORY, pin_module: Path = PIN_MODULE
) -> list[str]:
    """What on disk differs from what the sources render to (empty when in step)."""

    artifacts, manifest, pin_text = render(source)
    found = []
    held = _on_disk(directory)
    for path in sorted(set(artifacts) | set(held)):
        if path not in held:
            found.append(f"artifacts/{path}: missing")
        elif path not in artifacts:
            found.append(f"artifacts/{path}: not rendered from any source")
        elif held[path] != artifacts[path]:
            found.append(f"artifacts/{path}: differs")
    manifest_path = directory / "cruxible-kit.json"
    if not manifest_path.is_file() or manifest_path.read_bytes() != manifest:
        found.append("cruxible-kit.json: differs")
    if not pin_module.is_file() or pin_module.read_text(encoding="utf-8") != pin_text:
        found.append(f"{pin_module.name}: differs")
    return found


def write(
    source: Path = SOURCE, directory: Path = KIT_DIRECTORY, pin_module: Path = PIN_MODULE
) -> None:
    """Replace the kit directory's manifest and artifacts, and the pin module."""

    import shutil

    artifacts, manifest, pin_text = render(source)
    shutil.rmtree(directory / "artifacts", ignore_errors=True)
    for path, content in artifacts.items():
        target = directory / "artifacts" / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "cruxible-kit.json").write_bytes(manifest)
    pin_module.write_text(pin_text, encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="Fail when the bundled kit differs from its sources."
    )
    args = parser.parse_args(argv)
    if args.check:
        found = differences()
        if found:
            print("the bundled base kit differs from scripts/base_kit/:", file=sys.stderr)
            for line in found:
                print(f"  {line}", file=sys.stderr)
            print("run: python scripts/build_base_kit.py", file=sys.stderr)
            return 1
        print("base kit: in step with its sources")
        return 0
    write()
    artifacts, _manifest, _pin = render()
    print(f"base kit: {len(artifacts)} artifacts written to {KIT_DIRECTORY}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
